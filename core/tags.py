def tag_label(tag):
    return TAGS[tag][0] if tag in TAGS else tag


def tag_category(tag):
    return TAGS[tag][1] if tag in TAGS else "기타"


def all_tags():
    """분류 순서대로 정렬된 전체 태그 목록."""
    def key(t):
        cat = tag_category(t)
        idx = CATEGORY_ORDER.index(cat) if cat in CATEGORY_ORDER else 99
        return (idx, tag_label(t))
    return sorted(TAGS, key=key)


