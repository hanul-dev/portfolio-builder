def extract_tags(text):
    """공고문에서 역량 태그를 뽑는다."""
    if not text or not text.strip():
        return []
    low = text.lower()
    hits = []
    for tag, (_label, _cat, words) in TAGS.items():
        if any(w.lower() in low for w in words):
            hits.append(tag)
    return hits


def match_score(item_tags, jd_tags):
    """항목 태그가 공고 요구와 얼마나 겹치는지 (0~100)."""
    if not item_tags or not jd_tags:
        return 0
    hit = len([t for t in item_tags if t in jd_tags])
    return round(hit / len(item_tags) * 100)


def coverage(my_tags, jd_tags):
    """공고 요구 대비 충족률과 충족/미충족 태그를 함께 돌려준다."""
    jd = list(dict.fromkeys(jd_tags))
    if not jd:
        return 0, [], []
    hit = [t for t in jd if t in my_tags]
    miss = [t for t in jd if t not in my_tags]
    return round(len(hit) / len(jd) * 100), hit, miss


